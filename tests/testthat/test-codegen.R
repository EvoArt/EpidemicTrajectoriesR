  expect_match(s, "DiagEuclideanMetric(Float64[0.01, 0.02, 0.1] .^ 2)", fixed = TRUE)
})

test_that("a raw Julia kernel is passed straight through", {
  m <- toy_model()
  b <- c(toy_blocks(), list(et_kernel_julia("alpha", "MyKernel(1.0)")))
