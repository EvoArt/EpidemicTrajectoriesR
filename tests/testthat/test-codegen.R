# Tier 1: the generated Julia. No Julia session needed -- these read the source
# text, which is exactly what makes them cheap enough to run on every change.

src_of <- function(model = toy_model(), blocks = toy_blocks(), ...) {
  et_julia_source(model, blocks, ...)$src
}

test_that("the module is self-contained and correctly delimited", {
  s <- src_of(module_name = "ETRTest")
  expect_match(s, "^# Generated by EpidemicTrajectoriesR")
  expect_match(s, "\nmodule ETRTest\n", fixed = TRUE)
  expect_match(s, "\nend # module ETRTest\n", fixed = TRUE)
  for (u in c("using EpidemicTrajectories", "using PracticalBayes",
              "using PracticalEpiBayes", "import ADTypes")) {
    expect_match(s, u, fixed = TRUE)
  }
})

test_that("the module name is a function of the CONTENT", {
  # Same model, same module: a repeated et_loglik()/et_check_depends()/
  # et_sample() reuses the compiled module instead of recompiling the stack.
  a <- et_julia_source(toy_model(), toy_blocks())
  b <- et_julia_source(toy_model(), toy_blocks())
  expect_equal(a$module, b$module)
  expect_equal(a$src, b$src)
  # A changed model gets a different module.
  m2 <- toy_model(); m2$parameters$alpha <- prior(gamma_dist(2, 2), init = 0.05)
  expect_false(identical(et_julia_source(m2, toy_blocks())$module, a$module))
})

test_that("the header carries no timestamp", {
  # A varying header would make every generation a fresh module and force a
  # full recompile each time.
  expect_false(grepl("\\d{4}-\\d{2}-\\d{2}", strsplit(src_of(), "\n")[[1]][1]))
})

