test_that("a model with no observation process emits only the epidemic term", {
  f <- function(model, data, i, t) 1 / model$m
  d <- suppressMessages(et_data(
    n_individuals = TOY_N, n_timepoints = TOY_T,
    transitions = et_transitions(toy_states, "S -> I" = toy_infection,
                                 "I -> S" = toy_recovery),
    starting_state = toy_start, aggregates = toy_aggregate(),
    group = rep(seq_len(TOY_PENS), each = TOY_PER_PEN)))
  m <- et_model(data = d, parameters = list(
    alpha = prior(gamma_dist(1, 1), init = 0.05),
    beta  = prior(gamma_dist(1, 1), init = 0.05),
    m     = prior(gamma_dist(2, 4), init = 5.0),
    nu    = prior(beta_dist(1, 1), init = 0.1)))
  s <- et_julia_source(m)$src
  expect_match(s, "@addlogprob! loglik_fn(pars, data, X)", fixed = TRUE)
  expect_false(grepl("obs_loglik_fn", s, fixed = TRUE))
  expect_false(grepl("OBSLOGLIK", s, fixed = TRUE))
})

test_that("priors, deterministics and the trajectory block render in the model", {
  s <- src_of()
  expect_match(s, "alpha ~ Gamma(1.0, 1.0)", fixed = TRUE)
  expect_match(s, "m_tilde ~ Gamma(2.0, 4.0)", fixed = TRUE)
  expect_match(s, "m := m_tilde + 1", fixed = TRUE)
  expect_match(s, sprintf("X ~ TrajectoryLatent(%d, %d)", TOY_T, TOY_N),
               fixed = TRUE)
  # `pars` carries the derived name, because that is what the rate reads.
  expect_match(s, "m=m", fixed = TRUE)
})

