  expect_match(s, "function et_loglik_at(", fixed = TRUE)
  expect_match(s, "function et_iffbs_sweep(", fixed = TRUE)
  expect_match(s, "function et_check_depends(", fixed = TRUE)
  # The aggregates must agree with the STARTING trajectory before the first
  # likelihood call; that invariant is established once, here.
  expect_match(s, "reset_aggregates!(DATA)", fixed = TRUE)
  expect_match(s, "apply_derived_summaries!(et_params(INIT_PARS), DATA, X0)",
               fixed = TRUE)
  # The AD backend is a runtime argument, not a compile-time constant.
  expect_match(s, "adtype=ADTypes.AutoForwardDiff()", fixed = TRUE)
})
