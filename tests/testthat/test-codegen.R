  expect_match(et_julia_source(m, b)$src, ":alpha => MyKernel(1.0)", fixed = TRUE)
})

test_that("the entry gate is emitted only when asked for, with its survival", {
  f <- function(model, data, i, t) 1
  surv <- function(model, data, i, t) exp(-model$c1)
  d <- et_data(
    n_individuals = TOY_N, n_timepoints = TOY_T,
    transitions = et_transitions(c("S", "I", "D"),
                                 "S -> I" = toy_infection,
                                 survival = et_survival(surv, death = "D")),
    starting_state = toy_start,
    aggregates = et_aggregate(c("S", "I", "D"),
      arrays = list(n_infected = et_array("Int", c(TOY_PENS, TOY_T))),
      update = function(model, data, X, state, i, t) {
        n_infected[data$group[i], t] <- n_infected[data$group[i], t] + (state == "I")
      }),
    group = rep(seq_len(TOY_PENS), each = TOY_PER_PEN),
    observation_weight = toy_obs,
    extras = list(y = toy_y(), entry = rep(1L, TOY_N)))
  m0 <- et_model(data = d, parameters = list(
    alpha = prior(gamma_dist(1, 1), init = 0.05), beta = prior(gamma_dist(1, 1), init = 0.05),
    nu = prior(beta_dist(1, 1), init = 0.1), theta = prior(beta_dist(1, 1), init = 0.5),
    c1 = prior(exponential_dist(1), init = 0.1)))
  expect_match(et_julia_source(m0)$src, "et_loglik_for(DATA) = epidemic_loglik(DATA)",
               fixed = TRUE)

  m1 <- et_model(data = d, parameters = m0$parameters, entry_time = "entry")
  expect_match(et_julia_source(m1)$src,
               "epidemic_loglik(DATA; entry_time=Vector{Int}(entry), survival=et_survival_fn)",
               fixed = TRUE)
  # @survival must reach ET's macro with the death state named.
  expect_match(et_julia_source(m1)$src, "@survival et_survival_fn death=:D",
               fixed = TRUE)
})

test_that("a separate likelihood weight is wired to epidemic_obs_loglik", {
  filt <- function(model, data, X, i, t, s) model$eta * toy_obs(model, data, X, i, t, s)
  d <- et_data(
    n_individuals = TOY_N, n_timepoints = TOY_T,
    transitions = et_transitions(toy_states, "S -> I" = toy_infection,
                                 "I -> S" = toy_recovery),
    starting_state = toy_start, aggregates = toy_aggregate(),
    group = rep(seq_len(TOY_PENS), each = TOY_PER_PEN),
    observation_weight = filt, likelihood_weight = toy_obs,
    helpers = list(et_helper(toy_obs, "toy_obs")),
    extras = list(y = toy_y()))
  m <- et_model(data = d, parameters = list(
    alpha = prior(gamma_dist(1, 1), init = 0.05), beta = prior(gamma_dist(1, 1), init = 0.05),
    m = prior(gamma_dist(2, 4), init = 5), nu = prior(beta_dist(1, 1), init = 0.1),
    theta = prior(beta_dist(1, 1), init = 0.5), eta = prior(beta_dist(1, 1), init = 0.3)))
  g <- et_julia_source(m)
  expect_match(g$src,
               "epidemic_obs_loglik(DATA; observation_weight=et_obs_lik_weight)",
               fixed = TRUE)
  # `eta` is in the FILTER only, so it must not appear in the observation term's
  # dependency set -- the filter is never differentiated.
  expect_false("eta" %in% g$depends$observation)
  expect_true("theta" %in% g$depends$observation)
})

test_that("time-varying affected lists are built in the generated module", {
  gm <- matrix(rep(seq_len(TOY_PENS), each = TOY_PER_PEN), TOY_N, TOY_T)
  storage.mode(gm) <- "integer"
  d <- et_data(
    n_individuals = TOY_N, n_timepoints = TOY_T,
    transitions = et_transitions(toy_states, "S -> I" = toy_infection,
                                 "I -> S" = toy_recovery),
    starting_state = toy_start, aggregates = toy_aggregate(),
    group = rep(seq_len(TOY_PENS), each = TOY_PER_PEN),
    observation_weight = toy_obs,
    affected_individuals = et_affected_from_groups(gm),
    extras = list(y = toy_y()))
  m <- et_model(data = d, parameters = toy_model()$parameters,
                derived = list(m = quote(m_tilde + 1)))
  s <- et_julia_source(m)$src
  expect_match(s, "const affected_individuals = let gm = affected_groups", fixed = TRUE)
  expect_match(s, "affected_individuals=affected_individuals", fixed = TRUE)
  # The focal must be excluded from its own list, matching ET's default.
  expect_match(s, "[j for j in by_group[g, t] if j != i]", fixed = TRUE)
})

test_that("a conjugate-owned parameter gets a placeholder distribution", {
  d <- toy_data()
  m <- et_model(data = d, parameters = list(
    alpha = prior(gamma_dist(1, 1), init = 0.05), beta = prior(gamma_dist(1, 1), init = 0.05),
    m = prior(gamma_dist(2, 4), init = 5), theta = prior(beta_dist(1, 1), init = 0.5),
    nu = prior(init = c(0.05, 0.05, 0.05, 0.05), dim = c(2, 2), kind = "latent")))
  b <- list(et_conjugate_initial_state("nu", at = c(1, 2), states = c("S", "I"), n = 2),
            et_conjugate_test_sensitivity("theta", y = "y", infected_state = "I"))
  s <- et_julia_source(m, b)$src
  expect_match(s, "struct _ETPlaceholder_nu <: Distributions.DiscreteMatrixDistribution end",
               fixed = TRUE)
  expect_match(s, "Distributions.logpdf(::_ETPlaceholder_nu, ::AbstractMatrix) = 0.0",
               fixed = TRUE)
  expect_match(s, "nu ~ _ETPlaceholder_nu()", fixed = TRUE)
})

test_that("a vector or scalar latent parameter is refused with a useful message", {
  d <- toy_data()
  m <- et_model(data = d, parameters = list(
    alpha = prior(gamma_dist(1, 1), init = 0.05),
    nu = prior(init = c(0.1, 0.2), n = 2, kind = "latent")))
  expect_error(et_julia_source(m, list(
    et_conjugate("nu", "beta", c(1, 1), function(X, data, k) c(1, 1), n = 2))),
    "matrix-valued")
})

test_that("et_julia() bodies pass through and suppress depends= derivation", {
  d <- toy_data()
  d$observation_weight <- et_julia("return one(Float64)")
  m <- et_model(data = d, parameters = toy_model()$parameters,
                derived = list(m = quote(m_tilde + 1)))
  g <- et_julia_source(m)
  expect_match(g$src, "return one(Float64)", fixed = TRUE)
  # Unscannable body -> no annotation, which is PracticalBayes' safe default.
  expect_null(g$depends$observation)
  expect_false(grepl("obs_loglik_fn(pars, data, X)  depends", g$src, fixed = TRUE))
  # The epidemic term is unaffected and keeps its annotation.
  expect_false(is.null(g$depends$epidemic))
})

test_that("an et_julia() body WITH declared reads keeps the annotation", {
  d <- toy_data()
  d$observation_weight <- et_julia("return one(eltype(model.theta))",
                                   reads = "theta")
  m <- et_model(data = d, parameters = toy_model()$parameters,
                derived = list(m = quote(m_tilde + 1)))
  g <- et_julia_source(m)
  expect_equal(sort(g$depends$observation), sort(c("theta", "X")))
})

